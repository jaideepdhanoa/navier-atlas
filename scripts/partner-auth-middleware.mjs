// Generates Vercel Edge middleware for per-partner HTTP Basic auth.
// Public: /cluster/*, /city/*, /api/og, root atlas-data.js. Partner paths require password.
export function generatePartnerAuthMiddleware(partnerSlugs) {
  const slugs = [...partnerSlugs].sort();
  const matcher = slugs.flatMap((s) => [`/${s}`, `/${s}/:path*`]);

  return `// GENERATED by scripts/partner-auth-middleware.mjs — do not edit by hand.
import { next } from '@vercel/functions';

const PARTNER_SLUGS = new Set(${JSON.stringify(slugs)});

function envKey(slug) {
  return 'PARTNER_AUTH_' + slug.toUpperCase().replace(/-/g, '_');
}

let _authJson = null;
function authJson() {
  if (_authJson !== null) return _authJson;
  const raw = process.env.PARTNER_AUTH_JSON;
  if (!raw) { _authJson = {}; return _authJson; }
  try { _authJson = JSON.parse(raw); }
  catch { _authJson = {}; }
  return _authJson;
}

function passwordFor(slug) {
  const fromJson = authJson()[slug];
  if (fromJson) return fromJson;
  return process.env[envKey(slug)] || null;
}

function isPublic(pathname) {
  if (pathname === '/' || pathname === '/atlas-data.js' || pathname === '/index.html') return true;
  if (pathname.startsWith('/cluster/')) return true;
  if (pathname.startsWith('/city/')) return true;
  if (pathname.startsWith('/api/og')) return true;
  return false;
}

function partnerFromPath(pathname) {
  const seg = pathname.split('/').filter(Boolean)[0];
  return PARTNER_SLUGS.has(seg) ? seg : null;
}

function parseBasicAuth(header) {
  if (!header || !header.startsWith('Basic ')) return null;
  try {
    const decoded = atob(header.slice(6));
    const i = decoded.indexOf(':');
    if (i < 0) return null;
    return { user: decoded.slice(0, i), pass: decoded.slice(i + 1) };
  } catch { return null; }
}

async function sessionToken(slug, password) {
  const secret = process.env.AUTH_SECRET;
  if (!secret) return null;
  const enc = new TextEncoder();
  const key = await crypto.subtle.importKey(
    'raw', enc.encode(secret), { name: 'HMAC', hash: 'SHA-256' }, false, ['sign']
  );
  const sig = await crypto.subtle.sign('HMAC', key, enc.encode(slug + ':' + password));
  return btoa(String.fromCharCode(...new Uint8Array(sig)));
}

function sessionCookieName(slug) {
  return 'navier_partner_' + slug.replace(/-/g, '_');
}

function getCookie(request, name) {
  const raw = request.headers.get('cookie');
  if (!raw) return null;
  for (const part of raw.split(';')) {
    const eq = part.indexOf('=');
    if (eq < 0) continue;
    const k = part.slice(0, eq).trim();
    if (k === name) return decodeURIComponent(part.slice(eq + 1).trim());
  }
  return null;
}

async function hasValidSession(request, slug, password) {
  const expected = await sessionToken(slug, password);
  if (!expected) return false;
  return getCookie(request, sessionCookieName(slug)) === expected;
}

function unauthorized() {
  return new Response('Partner access requires a password.', {
    status: 401,
    headers: { 'WWW-Authenticate': 'Basic realm="Navier partner"' },
  });
}

export default async function middleware(request) {
  const { pathname } = new URL(request.url);
  if (isPublic(pathname)) return next();

  const slug = partnerFromPath(pathname);
  if (!slug) return next();

  const password = passwordFor(slug);
  if (!password) return next();

  if (await hasValidSession(request, slug, password)) return next();

  const creds = parseBasicAuth(request.headers.get('authorization'));
  if (creds && creds.pass === password) {
    const token = await sessionToken(slug, password);
    if (token) {
      const maxAge = 60 * 60 * 24 * 14;
      return next({
        headers: {
          'Set-Cookie': sessionCookieName(slug) + '=' + encodeURIComponent(token)
            + '; Path=/' + slug + '; HttpOnly; Secure; SameSite=Lax; Max-Age=' + maxAge,
        },
      });
    }
    return next();
  }

  return unauthorized();
}

export const config = {
  matcher: ${JSON.stringify(matcher)},
};
`;
}