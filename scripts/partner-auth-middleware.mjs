// Generates Vercel Edge middleware for per-partner HTTP Basic auth + /partners hub gate.
// Public: /cluster/*, /city/*, /employers/*, /bay-employers, /ny-employers, /api/og, /api/loi, root atlas-data.js.
export function generatePartnerAuthMiddleware(partnerSlugs) {
  const slugs = [...partnerSlugs].sort();
  // LB-258: listing every slug twice (/slug + /slug/:path*) blew the matcher table (~94 entries)
  // and Vercel's "Deploying outputs…" step failed. One path-to-regexp alternation covers all partners.
  const slugAlt = slugs.map((s) => s.replace(/-/g, '\\-')).join('|');
  const matcher = [
    '/invest',
    '/invest/:path*',
    '/teaser',
    '/teaser/:path*',
    '/partners',
    '/partners/:path*',
    `/:partner(${slugAlt})`,
    `/:partner(${slugAlt})/:path*`,
  ];

  return `// GENERATED by scripts/partner-auth-middleware.mjs — do not edit by hand.
import { next } from '@vercel/functions';

const PARTNER_SLUGS = new Set(${JSON.stringify(slugs)});
const HUB_SESSION_SLUG = '__partners_hub__';
const INVEST_SESSION_SLUG = '__invest__';
const TEASER_SESSION_SLUG = '__teaser__';
const INVEST_DEFAULT_PASSWORD = 'morpheus';
const TEASER_DEFAULT_PASSWORD = 'pioneer';

function envKey(slug) {
  return 'PARTNER_AUTH_' + slug.toUpperCase().replace(/-/g, '_');
}

let _authJson = null;
function authJson() {
  if (_authJson !== null) return _authJson;
  const raw = process.env.PARTNER_AUTH_JSON;
  if (!raw) { _authJson = {}; return _authJson; }
  try { _authJson = JSON.parse(raw); }
  catch { _authJson = {}; }
  return _authJson;
}

function passwordFor(slug) {
  const fromJson = authJson()[slug];
  if (fromJson) return fromJson;
  return process.env[envKey(slug)] || null;
}

function hubPassword() {
  return process.env.PARTNERS_HUB_PASSWORD || authJson().__hub__ || null;
}

function investPassword() {
  // Prefer Vercel env INVEST_PASSWORD; fall back to authored default so /invest is gated even before env is set.
  return process.env.INVEST_PASSWORD || authJson().__invest__ || INVEST_DEFAULT_PASSWORD;
}

function teaserPassword() {
  // Prefer Vercel env TEASER_PASSWORD; fall back to authored default so /teaser is gated even before env is set.
  return process.env.TEASER_PASSWORD || authJson().__teaser__ || TEASER_DEFAULT_PASSWORD;
}

function isPublic(pathname) {
  if (pathname === '/' || pathname === '/atlas-data.js' || pathname === '/index.html') return true;
  if (pathname.startsWith('/cluster/')) return true;
  if (pathname.startsWith('/city/')) return true;
  if (pathname.startsWith('/region/')) return true;
  // Employer sales hubs — public, not partner-auth gated
  if (pathname === '/bay-employers' || pathname.startsWith('/bay-employers/')) return true;
  if (pathname === '/ny-employers' || pathname.startsWith('/ny-employers/')) return true;
  if (pathname === '/employers' || pathname.startsWith('/employers/')) return true;
  if (pathname.startsWith('/api/og') || pathname.startsWith('/api/loi')) return true;
  return false;
}

function isPartnersHub(pathname) {
  return pathname === '/partners' || pathname.startsWith('/partners/');
}

function isInvest(pathname) {
  return pathname === '/invest' || pathname.startsWith('/invest/');
}

function isTeaser(pathname) {
  return pathname === '/teaser' || pathname.startsWith('/teaser/');
}

function partnerFromPath(pathname) {
  const seg = pathname.split('/').filter(Boolean)[0];
  return PARTNER_SLUGS.has(seg) ? seg : null;
}

function parseBasicAuth(header) {
  if (!header || !header.startsWith('Basic ')) return null;
  try {
    const decoded = atob(header.slice(6));
    const i = decoded.indexOf(':');
    if (i < 0) return null;
    return { user: decoded.slice(0, i), pass: decoded.slice(i + 1) };
  } catch { return null; }
}

async function sessionToken(slug, password) {
  const secret = process.env.AUTH_SECRET;
  if (!secret) return null;
  const enc = new TextEncoder();
  const key = await crypto.subtle.importKey(
    'raw', enc.encode(secret), { name: 'HMAC', hash: 'SHA-256' }, false, ['sign']
  );
  const sig = await crypto.subtle.sign('HMAC', key, enc.encode(slug + ':' + password));
  return btoa(String.fromCharCode(...new Uint8Array(sig)));
}

function sessionCookieName(slug) {
  if (slug === HUB_SESSION_SLUG) return 'navier_partners_hub';
  if (slug === INVEST_SESSION_SLUG) return 'navier_invest';
  if (slug === TEASER_SESSION_SLUG) return 'navier_teaser';
  return 'navier_partner_' + slug.replace(/-/g, '_');
}

function sessionCookiePath(slug) {
  if (slug === HUB_SESSION_SLUG) return '/partners';
  if (slug === INVEST_SESSION_SLUG) return '/invest';
  if (slug === TEASER_SESSION_SLUG) return '/teaser';
  return '/' + slug;
}

function getCookie(request, name) {
  const raw = request.headers.get('cookie');
  if (!raw) return null;
  for (const part of raw.split(';')) {
    const eq = part.indexOf('=');
    if (eq < 0) continue;
    const k = part.slice(0, eq).trim();
    if (k === name) return decodeURIComponent(part.slice(eq + 1).trim());
  }
  return null;
}

async function hasValidSession(request, slug, password) {
  const expected = await sessionToken(slug, password);
  if (!expected) return false;
  return getCookie(request, sessionCookieName(slug)) === expected;
}

function unauthorized(realm) {
  return new Response('Access requires a password.', {
    status: 401,
    headers: { 'WWW-Authenticate': 'Basic realm="' + realm + '"' },
  });
}

async function gate(request, slug, password, realm) {
  if (!password) return next();
  if (await hasValidSession(request, slug, password)) return next();
  const creds = parseBasicAuth(request.headers.get('authorization'));
  if (creds && creds.pass === password) {
    const token = await sessionToken(slug, password);
    if (token) {
      const maxAge = 60 * 60 * 24 * 14;
      return next({
        headers: {
          'Set-Cookie': sessionCookieName(slug) + '=' + encodeURIComponent(token)
            + '; Path=' + sessionCookiePath(slug) + '; HttpOnly; Secure; SameSite=Lax; Max-Age=' + maxAge,
        },
      });
    }
    return next();
  }
  return unauthorized(realm);
}

export default async function middleware(request) {
  const { pathname } = new URL(request.url);
  if (isPublic(pathname)) return next();

  if (isInvest(pathname)) {
    return gate(request, INVEST_SESSION_SLUG, investPassword(), 'Navier Series B');
  }

  if (isTeaser(pathname)) {
    return gate(request, TEASER_SESSION_SLUG, teaserPassword(), 'Navier Teaser');
  }

  if (isPartnersHub(pathname)) {
    return gate(request, HUB_SESSION_SLUG, hubPassword(), 'Navier partners');
  }

  const slug = partnerFromPath(pathname);
  if (!slug) return next();

  return gate(request, slug, passwordFor(slug), 'Navier partner');
}

export const config = {
  matcher: ${JSON.stringify(matcher)},
  // LB-258: edge middleware deploys to every region globally; any broken region fails the whole
  // deploy at "Deploying outputs…". nodejs runtime stays in the pinned vercel.json region (iad1).
  runtime: 'nodejs',
};
`;
}